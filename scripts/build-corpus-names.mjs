#!/usr/bin/env node
// Generates src/data/corpusNames.ts from the verified corpus, so the home
// screen can show real entry names rather than a hand-typed list that drifts.
//   node scripts/build-corpus-names.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const corpus = JSON.parse(readFileSync(new URL('../data/corpus.boston.json', import.meta.url), 'utf8'));
const rows = corpus.map(e => ({ name: e.name, type: e.type }));

const out = `// GENERATED by scripts/build-corpus-names.mjs — do not edit by hand.
// Real names from data/corpus.boston.json. The home screen shows these as
// evidence the corpus exists, so they must stay in sync with the file.
// Re-run: node scripts/build-corpus-names.mjs

export interface CorpusName {
  name: string;
  type: 'event' | 'person_org' | 'channel';
}

export const CORPUS_NAMES: CorpusName[] = ${JSON.stringify(rows, null, 2)};
`;

writeFileSync(new URL('../src/data/corpusNames.ts', import.meta.url), out);
console.log(`wrote src/data/corpusNames.ts — ${rows.length} names`);
